import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const app = await readFile(new URL('../../assets/js/app.js', import.meta.url), 'utf8');
const html = await readFile(new URL('../../index.html', import.meta.url), 'utf8');
const backup = await readFile(new URL('../../assets/js/learner-data-backup.js', import.meta.url), 'utf8');
const sw = await readFile(new URL('../../sw.js', import.meta.url), 'utf8');
assert.match(app, /import \{ createLearnerBackup, validateLearnerBackup \} from '\.\/learner-data-backup\.js'/);
assert.match(app, /store\.openCursor\(\)/, 'backup enumerates all current keys in the existing object store');
assert.match(app, /key\?\.startsWith\('toeic:'\)/, 'backup captures application localStorage namespace, including future and legacy keys');
assert.match(app, /navigator\.storage\.persist\(\)/, 'backup flow requests persistent browser storage when supported');
assert.match(app, /store\.put\(entry\.value,entry\.key\)/, 'restore merges imported keys without clearing unrelated keys');
assert.match(app, /store\.clear\(\);for\(const entry of current\.storage\.indexedDB\.entries\)/, 'failed cross-store restore attempts to roll IndexedDB back to the pre-import snapshot');
assert.doesNotMatch(app, /indexedDB\.open\(DB_NAME,\s*[2-9]/, 'existing IndexedDB version remains unchanged');
assert.match(html, /id="exportLearnerBackupButton"/);
assert.match(html, /id="restoreLearnerBackupButton"/);
assert.match(html, /id="learnerBackupFile"/);
assert.match(backup, /SHA-256/);
assert.match(backup, /TOEIC_LEARNER_DATA_BACKUP/);
assert.match(sw, /\.\/assets\/js\/learner-data-backup\.js/, 'new module is included in both required and app-shell offline precache lists');
console.log('PASS: full-backup UI and app integration, dynamic storage enumeration, persistent-storage request, merge restore, rollback guard and unchanged IndexedDB schema.');
