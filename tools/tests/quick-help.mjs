import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'assets/js/app.js'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const tombstone=fs.readFileSync(path.join(root,'assets/js/quick-help.js'),'utf8');
assert.ok(index.includes('id="quickHelpLauncher"')&&index.includes('id="quickHelpPanel"'));
assert.ok(!/Hướng dẫn sử dụng|quickHelpGuide|data-quick-help-guide/.test(index));
assert.ok(!/quickHelpWordSearch|findVocabularyPrefixMatches|maskVocabularyHeadword/.test([index,app].join('\n')));
assert.match(tombstone,/intentionally executes nothing/i);
assert.ok(sw.includes('./assets/js/quick-help.js'));
console.log('PASS: legacy Quick Help UI paths are retained only for safe PWA compatibility; usage guide and prefix search remain retired.');
