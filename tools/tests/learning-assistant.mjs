import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const source=fs.readFileSync(path.join(root,'assets/js/learning-assistant.js'),'utf8');
const app=fs.readFileSync(path.join(root,'assets/js/app.js'),'utf8');
assert.match(source,/Intentionally executes nothing/i,'The former progress-aware helper must remain a safe compatibility tombstone.');
assert.ok(!app.includes("from './learning-assistant.js'"),'The live app must not import the retired learner-progress assistant.');
assert.ok(!app.includes('buildCompanionSnapshot')&&!app.includes('hasLearningFootprint'));
console.log('PASS: retired progress-reading learning assistant is a no-op compatibility tombstone.');
