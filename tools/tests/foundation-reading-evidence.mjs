import assert from 'node:assert/strict';
import { recordFoundationReadingAttempt, summarizeFoundationReading } from '../../assets/js/foundation-reading-evidence.js';
let progress = {};
progress = recordFoundationReadingAttempt(progress, 'pa1-alphabet', 'pa1-alphabet::reading1::q1', true, 100);
let summary = summarizeFoundationReading(progress, 'pa1-alphabet');
assert.equal(summary.uniqueQuestions, 1);
assert.equal(summary.status, 'insufficient_evidence');
progress = recordFoundationReadingAttempt(progress, 'pa1-alphabet', 'pa1-alphabet::reading1::q1', false, 200);
summary = summarizeFoundationReading(progress, 'pa1-alphabet');
assert.equal(summary.uniqueQuestions, 1, 'retry must not inflate unique question count');
assert.equal(summary.accuracyPercent, 0, 'latest result must replace prior result for accuracy');
assert.equal(summary.totalAttempts, 2);
progress = recordFoundationReadingAttempt(progress, 'pa1-alphabet', 'pa1-alphabet::reading1::q2', true, 300);
summary = summarizeFoundationReading(progress, 'pa1-alphabet');
assert.equal(summary.uniqueQuestions, 2);
assert.equal(summary.accuracyPercent, 50);
assert.equal(summary.status, 'in_progress');
progress = recordFoundationReadingAttempt(progress, 'pa1-alphabet', 'pa1-alphabet::reading1::q1', true, 400);
summary = summarizeFoundationReading(progress, 'pa1-alphabet');
assert.equal(summary.uniqueQuestions, 2);
assert.equal(summary.accuracyPercent, 100);
assert.equal(summary.status, 'practice_threshold_met');
let thresholdProgress = {};
thresholdProgress = recordFoundationReadingAttempt(thresholdProgress, 'a2-example', 'q1', true, 500);
thresholdProgress = recordFoundationReadingAttempt(thresholdProgress, 'a2-example', 'q2', true, 600);
thresholdProgress = recordFoundationReadingAttempt(thresholdProgress, 'a2-example', 'q3', false, 700);
const a2Threshold = summarizeFoundationReading(thresholdProgress, 'a2-example', { minimumUniqueQuestions: 3, practiceAccuracyThreshold: 0.67 });
assert.equal(a2Threshold.accuracyPercent, 67);
assert.equal(a2Threshold.status, 'practice_threshold_met', 'rounded 67% should match the visible 67% threshold');
assert.equal(summarizeFoundationReading(progress, 'a1-office-cafe').uniqueQuestions, 0);
console.log('Foundation reading evidence: PASS');
